<h2>Three Weeks After September 11</h2>
<p>America was still holding its breath. The twin towers had fallen twenty-two days earlier. Box cutters had become the most feared objects in the country's transit system. And at four in the morning on October 3, 2001, a man on a Greyhound bus pulled one out.</p>
<p>The bus was travelling eastbound on Interstate 24, cutting through the dark, rural stretch of middle Tennessee between Nashville and Chattanooga. It had left Chicago the previous day, bound for Orlando, Florida, with thirty-nine passengers aboard. Most of them were asleep. The man who would kill six of them had been awake for hours, pacing the aisle, asking questions no one could satisfactorily answer.</p>

<hr>
<h2>The Man in the Aisle</h2>
<p>His name was Damir Igrić. He was twenty-nine years old, born on September 21, 1972, in Slavonski Brod, a city in what was then Yugoslavia and is now Croatia. As a teenager he trained as a locksmith in vocational school. At nineteen, when Croatia's war of independence erupted, he joined the army. He was discharged two years later. The Croatian ambassador to the United States, Ivan Grdešić, would later describe the reason bluntly: "violent behavior and substance abuse... he was connected with crimes in Croatia."</p>
<p>Igrić arrived in the United States in March 1999, entering through Miami on a thirty-day transit visa. He never left. For two years he overstayed, telling immigration officials he had relatives in Florida and New York. He found work in a restaurant in New York City. Those who knew him in that period described a man with a long, documented history of mental illness — a history that no visa screening had flagged and no employer had caught.</p>
<p>On the night of October 2, he boarded the Greyhound in Chicago. Passenger Carly Rinearson, seated directly behind the driver, noticed him almost immediately. He approached her more than once, asking what time it was, then asking if he could have her seat. She refused. He returned to the back of the bus. An hour passed. Then he walked to the front again.</p>

<hr>
<h2>Four in the Morning</h2>
<p>Driver Garfield Sands, a Greyhound veteran running the Indianapolis-to-Atlanta leg of the route, had already fielded Igrić's questions three times. How much longer until the next stop? Manchester, Sands told him. Go back to your seat.</p>
<p>The fourth time Igrić came forward, he said nothing. He produced a utility knife — the kind of box cutter that had, three weeks earlier, been used to hijack four commercial airliners — and slashed Sands across the throat. Then he lunged for the steering wheel.</p>
<p>Sands fought. The bus swerved across the eastbound lanes, crossed the median, barrelled through the westbound traffic, and rolled onto its left side in the ditch beyond the highway. Igrić was thrown through the windshield. He died on impact.</p>
<p>Six passengers were killed in the crash: Matthew Hawkins, 29, of Pierceton, Indiana; Tommy Montgomery, 52, of Huntsville, Alabama; Marian Nalls, 75, of Euclid, Ohio; Amelia Nerio, 73, of Lake Wales, Florida; and Fannie Jones, 68, of Stone Mountain, Georgia. Twenty-two others were injured, ranging from bruises to wounds requiring emergency surgery.</p>
<p>Sands, bleeding from his slashed throat, crawled out through a window. He ran roughly two hundred yards up the dark highway, flagging down passing vehicles for help. He survived.</p>

