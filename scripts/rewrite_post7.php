<h2>Not Terrorism — But the Fear Was Real</h2>
<p>Greyhound Lines, the largest scheduled bus operator in the United States, did what no one had seen before: it shut down its entire fleet. Every bus, every route, every terminal — dark. CEO Craig Lentzsch called it a precaution. In the post-9/11 atmosphere, no one argued.</p>
<p>The FBI moved fast. Special Agent R. Joe Clark, speaking to reporters at the crash site within hours, identified Igrić and declared the attack "an isolated act by a single, deranged individual." No terrorist connection. No co-conspirators. No manifesto. The U.S. Justice Department concurred. By mid-afternoon, Greyhound resumed service.</p>
<p>But the timing made the distinction almost irrelevant. A box cutter. A foreign national. A hijacking attempt on a commercial vehicle. In October 2001, those words together were enough to freeze a nation's largest bus company for six hours. The attack was random, the FBI insisted. The fear it produced was not.</p>

<hr>
<h2>The Lawsuit That Followed</h2>
<p>In the years after the crash, victims and their families pursued civil litigation against Greyhound Lines. The central claim, detailed in the September 2005 issue of <i>The Tennessee Jury Verdict Reporter</i>, was negligent bus security: that Greyhound had failed to implement reasonable measures to protect passengers from violent acts by fellow travellers. The case raised questions about boarding procedures, passenger screening, and the duty of care a common carrier owes to people who hand over their safety for the price of a ticket.</p>
<p>The litigation highlighted a gap in American transit security that the post-9/11 focus on aviation had left wide open. Airports got metal detectors, reinforced cockpit doors, and the Transportation Security Administration. Bus stations got very little. The Igrić attack became a case study in what happens when that gap is exploited — even unintentionally, even by a single disturbed man with no political motive.</p>

<hr>
<h2>A Question Without an Answer</h2>
<p>Damir Igrić left no note, no recording, no explanation. The FBI found no ideological motive, no connection to any organisation, no evidence of premeditation beyond the purchase of a utility knife. He had a history of mental illness, a discharged military record marked by violence, and two years of undocumented life in a country that had not asked him many questions.</p>
<p>Why he chose that bus, that driver, that moment on a dark stretch of Tennessee highway at four in the morning — none of the official reports say. The five people who died beside him on Interstate 24 were strangers. They were sleeping. They never knew what was coming.</p>
